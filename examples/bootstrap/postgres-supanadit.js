// ===========================================================================
// init/01-directories
// ===========================================================================
function createDirectories() {
  for (const d of [PGDATA, PGCONFIG, PGRUN]) {
    fs.mkdirAll(d, 0o755);
    fs.chmod(d, 0o755);
  }
  fs.chmod(PGDATA, 0o700);
  if (PGBACKREST_ENABLE) {
    fs.mkdirAll(PGBACKUP, 0o750);
    fs.chmod(PGBACKUP, 0o750);
    for (const s of ["spool", "log", "lock"]) {
      fs.mkdirAll(PGBACKUP + "/" + s, 0o750);
      fs.chmod(PGBACKUP + "/" + s, 0o750);
    }
  }
}

// ===========================================================================
// init/02-database: initdb, password, replication user, HA clone, restore
// ===========================================================================
function runPg(cmd, name) {
  const p = process.spawn({
    name: name || "pg",
    process: { binaryPath: "/bin/sh", arguments: ["-c", cmd], user: PG_USER, group: PG_GROUP },
  });
  p.start([]);
  return p.wait();
}

function quoteArg(a) { return "'" + String(a).replace(/'/g, "'\\''") + "'"; }

function clusterExists() {
  return ["PG_VERSION", "postgresql.conf", "pg_hba.conf"].some((f) => fs.exists(PGDATA + "/" + f));
}

function clonePrimary() {
  const host = env.get("PRIMARY_HOST");
  if (!host) throw new Error("PRIMARY_HOST required for replica");
  const cmd = "PGPASSWORD=" + quoteArg(env.get("REPLICATION_PASSWORD")) +
    " pg_basebackup -h " + host + " -p " + env.get("PRIMARY_PORT", "5432") +
    " -U " + env.get("REPLICATION_USER", "replicator") + " -D " + quoteArg(PGDATA) + " -Fp -Xs -R";
  if (runPg(cmd, "pg_basebackup") !== 0) throw new Error("pg_basebackup failed");
}

function setPassword() {
  if (!PG_PASS) return;
  const cfg = fs.tempFile("/tmp", "pg_pw");
  editor.open(cfg).replace("listen_addresses = 'localhost'\nport = 5433\npassword_encryption = scram-sha-256\n");
  runPg("pg_ctl -D " + quoteArg(PGDATA) + " -o \"--config-file=" + cfg + "\" -s start", "pw-start");
  runPg("sleep 2", "pw-wait");
  runPg("psql -h localhost -p 5433 -U postgres -d postgres -c " + quoteArg("ALTER USER postgres PASSWORD '" + PG_PASS.replace(/'/g, "''") + "';"), "pw-set");
  runPg("pg_ctl -D " + quoteArg(PGDATA) + " -s stop", "pw-stop");
  fs.remove(cfg);
}

function initdb() {
  if (clusterExists()) { log.info("Cluster exists, skipping initdb"); return; }
  if (PATRONI_ENABLE) return;
  if (HA_MODE === "native" && REPL_ROLE === "replica") { clonePrimary(); return; }

  const args = ["--auth=trust", "--username=postgres", "--encoding=UTF-8", "--locale=C"];
  if (env.get("POSTGRES_INITDB_ARGS")) args.push(...env.get("POSTGRES_INITDB_ARGS").split(/\s+/));
  if (env.get("POSTGRES_INITDB_WALDIR")) args.push("--waldir=" + env.get("POSTGRES_INITDB_WALDIR"));
  args.push("--pgdata=" + PGDATA);
  if (runPg("initdb " + args.map(quoteArg).join(" "), "initdb") !== 0) throw new Error("initdb failed");
  fs.chmod(PGDATA, 0o700);
  setPassword();
}

// pgBackRest restore (declarative arg building from env).
function performRestore() {
  if (!PGBACKREST_ENABLE) throw new Error("PGBACKREST_RESTORE requires PGBACKREST_ENABLE");
  const args = ["--config=/etc/pgbackrest.conf", "--stanza=" + STANZA, "restore"];
  const opt = (v, f) => { if (v) args.push("--" + f + "=" + v); };
  const flag = (v, f) => { if (env.isTruthy(v)) args.push("--" + f); };
  opt(env.get("PGBACKREST_RESTORE_TYPE"), "type");
  opt(env.get("PGBACKREST_RESTORE_TARGET"), "target");
  opt(env.get("PGBACKREST_RESTORE_TARGET_TIMELINE"), "target-timeline");
  opt(env.get("PGBACKREST_RESTORE_TARGET_ACTION"), "target-action");
  opt(env.get("PGBACKREST_RESTORE_SET"), "set");
  opt(env.get("PGBACKREST_RESTORE_TABLESPACE_MAP"), "tablespace-map");
  opt(env.get("PGBACKREST_RESTORE_DB_INCLUDE"), "db-include");
  opt(env.get("PGBACKREST_RESTORE_DB_EXCLUDE"), "db-exclude");
  flag("PGBACKREST_RESTORE_TARGET_IMMEDIATE", "target-immediate");
  flag("PGBACKREST_RESTORE_LINK_ALL", "link-all");
  if (env.isTruthy(env.get("PGBACKREST_RESTORE_DELTA", "true"))) args.push("--delta");
  flag("PGBACKREST_RESTORE_FORCE", "force");
  fs.mkdirAll(PGDATA, 0o700);
  fs.chmod(PGDATA, 0o700);
  if (runPg("env -u PGBACKREST_ENABLE pgbackrest " + args.map(quoteArg).join(" "), "restore") !== 0) {
    throw new Error("pgBackRest restore failed");
  }
  if (fs.exists(RESTORE_SENTINEL)) fs.remove(RESTORE_SENTINEL);
}

// ===========================================================================
// init/03-config — DECLARATIVE FileProvision (drives config generation)
// ===========================================================================
const postgresFiles = [
  // postgresql.conf: create once if missing, then env overrides (smart-quoted).
  { path: POSTGRES_CONF, createOnly: true, operations: [{ type: "replace", value: postgresqlConfTemplate }] },
  {
    path: POSTGRES_CONF,
    operations: [
      { type: "set-property", fromEnvPattern: "^POSTGRESQL_CONFIG_(.+)$", nameTransform: "lower",
        pattern: "^\\s*#?\\s*${name}\\s*=.*", value: "${name} = ${value}", valueFormat: "auto" },
      { type: "set-property", fromEnv: "POSTGRESQL_SHARED_BUFFERS", pattern: "^shared_buffers\\s*=.*", value: "shared_buffers = ${value}", valueFormat: "auto" },
      { type: "set-property", fromEnv: "POSTGRESQL_MAX_CONNECTIONS", pattern: "^max_connections\\s*=.*", value: "max_connections = ${value}", valueFormat: "auto" },
      { type: "set-property", fromEnv: "POSTGRESQL_LISTEN_ADDRESSES", pattern: "^listen_addresses\\s*=.*", value: "listen_addresses = ${value}", valueFormat: "auto" },
      { type: "set-property", fromEnv: "POSTGRESQL_WORK_MEM", pattern: "^work_mem\\s*=.*", value: "work_mem = ${value}", valueFormat: "auto" },
    ],
  },
  // pg_hba.conf: default once if missing, then external-access + PG_HBA_ADD_*.
  { path: PG_HBA, createOnly: true, operations: [{ type: "replace", value: pgHbaTemplate }] },
  {
    path: PG_HBA,
    operations: [
      { type: "set-property", when: { name: "EXTERNAL_ACCESS_ENABLE", value: "true" },
        pattern: "^host\\s+all\\s+all\\s+0\\.0\\.0\\.0/0.*", value: "host    all             all             0.0.0.0/0               " + env.get("EXTERNAL_ACCESS_METHOD", "md5") },
      { type: "append", fromEnvPattern: "^PG_HBA_ADD_([0-9]+)$", value: "${value}" },
    ],
  },
  // pgbackrest.conf: generated by JS (domain-specific PGBACKREST_* mapping,
  // e.g. REPO_* -> repo1-*, is not expressible as a generic NameTransform).
  {
    path: PGBACKREST_CONF,
    when: { name: "PGBACKREST_ENABLE", value: "true" },
    operations: [{ type: "replace", value: pgbackrestConfig() }],
  },
  // patroni.yml (template literal, conditional on PATRONI_ENABLE).
  { path: PATRONI_CONF, when: { name: "PATRONI_ENABLE", value: "true" }, operations: [{ type: "replace", value: patroniYaml }] },
  // sshd_config.
  { path: SSHD_CONF, operations: [{ type: "replace", value: sshdTemplate }] },
  // pgbouncer.ini env sub (only if enabled).
  {
    path: PGBOUNCER_INI,
    when: { name: "PGBOUNCER_ENABLE", value: "true" },
    operations: [{ type: "set-property", fromEnvPattern: "^PGBOUNCER_CONFIG_(.+)$", nameTransform: "lower", pattern: "^${name}\\s*=.*", value: "${name} = ${value}" }],
  },
];

// ===========================================================================
// init/05-sshd keys
// ===========================================================================
function sshdKeys() {
  const run = "/run/ssh";
  fs.mkdirAll(run, 0o755);
  if (!fs.exists(run + "/ssh_host_rsa_key")) runPg("ssh-keygen -A", "ssh-keygen");
  const dir = "/home/postgres/.ssh";
  fs.mkdirAll(dir, 0o700);
  fs.chmod(dir, 0o700);
  if (!fs.exists(dir + "/id_rsa")) {
    runPg("ssh-keygen -t rsa -b 4096 -f " + dir + "/id_rsa -N '' -C 'replica'", "ssh-key");
    fs.chmod(dir + "/id_rsa", 0o600);
  }
  if (fs.exists(dir + "/id_rsa.pub") && !fs.exists(dir + "/authorized_keys")) {
    editor.open(dir + "/authorized_keys").replace(editor.open(dir + "/id_rsa.pub").read().trim() + "\n");
  }
}

// ===========================================================================
// Runtime: mode selection + declarative supervision
// ===========================================================================
function isPrimary() { return !(REPL_ROLE === "replica"); }

function startPgbouncer() {
  if (!PGBOUNCER_ENABLE) return null;
  if (!fs.exists(PGBOUNCER_INI)) throw new Error("pgbouncer.ini not found: " + PGBOUNCER_INI);
  const p = process.spawn({
    name: "pgbouncer",
    process: { binaryPath: "pgbouncer", arguments: ["-d", PGBOUNCER_INI], user: PG_USER, group: PG_GROUP },
  });
  p.start([]);
  return p;
}

function startSshd() {
  if (!isPrimary() || !fs.exists("/usr/sbin/sshd")) return null;
  const p = process.spawn({ name: "sshd", process: { binaryPath: "/usr/sbin/sshd" } });
  p.start([]);
  return p;
}

function startBackupScheduler(parent) {
  if (!PGBACKREST_ENABLE || !PGBACKREST_AUTO) return null;
  const p = process.spawn({ name: "backup-scheduler", process: { binaryPath: "/opt/container/entrypoint.d/scripts/runtime/backup-scheduler.sh", arguments: [] } });
  p.start([]);
  return p;
}

function startSleep() {
  chain.run({ roots: [{
    name: "sleep",
    process: { binaryPath: "/bin/sh", arguments: ["-c", "while true; do sleep 3600; done"] },
    restart: { mode: "always", backoff: 1000 * 1e6 },
  }] });
}

function startDatabase() {
  const mainProcess = PATRONI_ENABLE
    ? { binaryPath: "patroni", arguments: [PATRONI_CONF], user: PG_USER, group: PG_GROUP }
    : { binaryPath: env.get("POSTGRES_BIN", "postgres"), arguments: ["-D", PGDATA], user: PG_USER, group: PG_GROUP };

  const node = {
    name: PATRONI_ENABLE ? "patroni" : "postgres",
    process: mainProcess,
    files: postgresFiles,
    forwardSignals: ["SIGTERM", "SIGINT", "SIGHUP", "SIGUSR1", "SIGUSR2"],
    shutdown: { timeout: 30 * 1e9, forceKill: true },
  };

  // Health server mode: keep ezx alive, gate /readyz.
  const healthAddr = env.get("EZX_HEALTH_ADDR");
  if (healthAddr) {
    node.health = { readyProbe: { type: "tcp", tcp: { host: "127.0.0.1", port: parseInt(PG_PORT, 10) } } };
    chain.run({ roots: [node] });
    return;
  }

  // Exec mode: the main process replaces ezx as PID 1 (no children to supervise).
  process.exec(node);
}

// ===========================================================================
// Main
// ===========================================================================
function main() {
  fs.umask(0o027);
  createDirectories();
  initdb();

  // Config is generated declaratively when the process tree starts (postgresFiles).
  sshdKeys();

  if (fs.exists(RESTORE_SENTINEL)) performRestore();

  if (SLEEP_MODE) { log.info("Sleep mode"); startSleep(); return; }
  startDatabase();
  log.info("Entrypoint complete");
}

main();
