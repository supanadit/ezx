// pgBackRest config: domain-specific env mapping (REPO_* -> repo1-*, snake to
// kebab, plus truthy flags -> "=y"). Not expressible as a generic NameTransform.
function pgbackrestConfig() {
  const lines = [];
  const stanza = STANZA;
  const repoType = env.get("PGBACKREST_REPO_TYPE", env.get("PGBACKREST_REPO1_TYPE", "posix"));
  const repoPath = env.get("PGBACKREST_REPO_PATH", env.get("PGBACKREST_REPO1_PATH"));
  const add = (envName, key) => { const v = env.get(envName); if (v) lines.push(key + "=" + v); };
  const addFlag = (envName, key) => { if (env.isTruthy(envName)) lines.push(key + "=y"); };

  // [global]
  lines.push("# pgBackRest configuration generated by container");
  lines.push("[global]");
  lines.push("repo1-retention-full=" + env.get("PGBACKREST_REPO_RETENTION_FULL", env.get("PGBACKREST_REPO1_RETENTION_FULL", "2")));
  lines.push("repo1-retention-diff=" + env.get("PGBACKREST_REPO_RETENTION_DIFF", env.get("PGBACKREST_REPO1_RETENTION_DIFF", "6")));
  lines.push("log-level-console=info");
  lines.push("log-level-file=debug");
  lines.push("log-path=" + PGBACKUP + "/log");
  lines.push("lock-path=" + PGBACKUP + "/lock");
  lines.push("spool-path=" + PGBACKUP + "/spool");
  add("PGBACKREST_REPO_RETENTION_FULL_TYPE", "repo1-retention-full-type");
  add("PGBACKREST_PROCESS_MAX", "process-max");
  addFlag("PGBACKREST_ARCHIVE_ASYNC", "archive-async");
  add("PGBACKREST_REPO_COMPRESSION", "repo1-compression");

  // repo section
  lines.push("");
  lines.push("# Repository 1 configuration");
  lines.push("repo1-type=" + repoType);
  if (repoType === "posix" || repoType === "filesystem") {
    lines.push("repo1-path=" + (repoPath || PGBACKUP));
  } else if (repoType === "s3") {
    add("PGBACKREST_REPO_S3_BUCKET", "repo1-s3-bucket");
    add("PGBACKREST_REPO_S3_ENDPOINT", "repo1-s3-endpoint");
    add("PGBACKREST_REPO_S3_KEY", "repo1-s3-key");
    add("PGBACKREST_REPO_S3_KEY_SECRET", "repo1-s3-key-secret");
    lines.push("repo1-path=" + (repoPath || "/pgbackrest"));
  } else if (repoType === "gcs") {
    add("PGBACKREST_REPO_GCS_BUCKET", "repo1-gcs-bucket");
    lines.push("repo1-path=" + (repoPath || "/pgbackrest"));
  } else {
    lines.push("repo1-path=" + (repoPath || "/pgbackrest"));
  }

  // standby backup
  const standby = backupStandby(env.get("PGBACKREST_BACKUP_STANDBY"));
  if (standby) lines.push("backup-standby=" + standby);

  // stanza
  lines.push("");
  lines.push("[" + stanza + "]");
  lines.push("pg1-path=" + PGDATA);
  lines.push("pg1-port=" + PG_PORT);
  lines.push("pg1-user=" + PG_USER);
  lines.push("pg1-socket-path=" + PGRUN);
  add("PGBACKREST_PASSWORD", "pg1-password");
  return lines.join("\n") + "\n";
}

