// ezx bootstrap examples/bootstrap/postgres-supanadit.js
//
// A 1:1 behavioural port of the production PostgreSQL container entrypoint
// (container-scripts/docker/postgresql), expressed the ezx way: declarative
// FileProvision for env→config mapping, Go-backed env/fs/editor/probe
// primitives, template literals for static skeletons, and a declarative
// ProcessChain for multi-process supervision. No bash reimplementation in JS.
//
//   entrypoint.sh        -> main() below
//   init/00-misc-scripts -> fs.symlink
//   init/01-directories  -> fs.mkdirAll / fs.chmod / fs.chownRecursive
//   init/02-database     -> process.spawn (initdb, psql, pg_basebackup)
//   init/03-config       -> declarative FileProvision on the postgres node
//   init/04-backup       -> declarative FileProvision (PGBACKREST_* fromEnv)
//   init/05-sshd         -> FileProvision template
//   runtime/startup      -> chain.run (postgres + pgbouncer + sshd + scheduler)
//   runtime/healthcheck  -> health.readyProbe + ezx.probe
//   runtime/shutdown     -> orchestrator ShutdownConfig + ForwardSignals
//   (reaper)             -> handled silently by ezx (PID 1 init)
//
// Requires a postgres image with /opt/container/entrypoint.d and postgres
// installed. Run: ezx bootstrap postgres-supanadit.js
