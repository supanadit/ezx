// pgbouncer.ini: generated declaratively from the PGBOUNCER_* defaults,
// replacing the bash sed placeholder substitution. PGBOUNCER_CONFIG_* overrides
// are applied on top via the set-property FileProvision below.
function pgbouncerConfig() {
	const b = config.builder({ separator: " = " });
	b.section("databases").set("*", "host=localhost port=" + PG_PORT);
	b.blank();
	const p = b.section("pgbouncer");
	p.set("listen_addr", PGBOUNCER_LISTEN_ADDR);
	p.set("listen_port", PGBOUNCER_LISTEN_PORT);
	p.set("unix_socket_dir", PGRUN);
	p.set("auth_type", PGBOUNCER_AUTH_TYPE);
	p.set("auth_file", "/etc/pgbouncer/userlist.txt");
	p.set("admin_users", PGBOUNCER_ADMIN_USERS);
	p.set("stats_users", PGBOUNCER_STATS_USERS);
	p.set("pool_mode", PGBOUNCER_POOL_MODE);
	p.set("max_client_conn", PGBOUNCER_MAX_CLIENT_CONN);
	p.set("default_pool_size", PGBOUNCER_DEFAULT_POOL_SIZE);
	p.set("logfile", "/var/log/pgbouncer/pgbouncer.log");
	p.set("pidfile", "/var/run/pgbouncer/pgbouncer.pid");
	p.set("user", "postgres");
	return b.build();
}

// Patroni etcd hosts, normalized to host:port strings.
function etcdHosts() {
	const hosts = env
		.get(
			"PATRONI_ETCD_HOSTS",
			env.get("ETCD_HOSTS", env.get("ETCD_HOST", "localhost")),
		)
		.replace(/;/g, ",")
		.split(",")
		.map((s) => s.trim())
		.filter(Boolean);
	const port = env.get("ETCD_PORT", "2379");
	return hosts.map((h) => (h.includes(":") ? h : h + ":" + port));
}

