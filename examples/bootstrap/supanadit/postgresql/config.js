// pgBackRest config: domain-specific env mapping (REPO_* -> repo1-*, snake to
// kebab, plus truthy flags -> "=y"). Not expressible as a generic NameTransform.
function backupStandby(value) {
	switch ((value || "").toLowerCase()) {
		case "y":
		case "yes":
		case "1":
		case "on":
		case "true":
			return "y";
		case "prefer":
			return "prefer";
		case "n":
		case "no":
		case "0":
		case "off":
		case "false":
			return "n";
		default:
			return "";
	}
}

function pgbackrestConfig() {
	const repoType = env.get(
		"PGBACKREST_REPO_TYPE",
		env.get("PGBACKREST_REPO1_TYPE", "posix"),
	);
	const repoPath = env.get(
		"PGBACKREST_REPO_PATH",
		env.get("PGBACKREST_REPO1_PATH"),
	);

	const b = config.builder({ separator: "=", valueFormat: "none" });

	// [global]
	b.comment("pgBackRest configuration generated by container");
	const global = b.section("global");
	global.set(
		"repo1-retention-full",
		env.get(
			"PGBACKREST_REPO_RETENTION_FULL",
			env.get("PGBACKREST_REPO1_RETENTION_FULL", "2"),
		),
	);
	global.set(
		"repo1-retention-diff",
		env.get(
			"PGBACKREST_REPO_RETENTION_DIFF",
			env.get("PGBACKREST_REPO1_RETENTION_DIFF", "6"),
		),
	);
	global.set("log-level-console", "info");
	global.set("log-level-file", "debug");
	global.set("log-path", PGBACKUP + "/log");
	global.set("lock-path", PGBACKUP + "/lock");
	global.set("spool-path", PGBACKUP + "/spool");
	global.setFromEnv("PGBACKREST_REPO_RETENTION_FULL_TYPE", "repo1-retention-full-type");
	global.setFromEnv("PGBACKREST_PROCESS_MAX", "process-max");
	global.setFlag("archive-async", env.isTruthy("PGBACKREST_ARCHIVE_ASYNC"));
	global.setFromEnv("PGBACKREST_REPO_COMPRESSION", "repo1-compression");

	// repo section (no INI header, matches original bare comment+key output)
	b.blank();
	b.comment("Repository 1 configuration");
	b.set("repo1-type", repoType);
	if (repoType === "posix" || repoType === "filesystem") {
		b.set("repo1-path", repoPath || PGBACKUP);
	} else if (repoType === "s3") {
		b.setFromEnv("PGBACKREST_REPO_S3_BUCKET", "repo1-s3-bucket");
		b.setFromEnv("PGBACKREST_REPO_S3_ENDPOINT", "repo1-s3-endpoint");
		b.setFromEnv("PGBACKREST_REPO_S3_KEY", "repo1-s3-key");
		b.setFromEnv("PGBACKREST_REPO_S3_KEY_SECRET", "repo1-s3-key-secret");
		b.set("repo1-path", repoPath || "/pgbackrest");
	} else if (repoType === "gcs") {
		b.setFromEnv("PGBACKREST_REPO_GCS_BUCKET", "repo1-gcs-bucket");
		b.set("repo1-path", repoPath || "/pgbackrest");
	} else {
		b.set("repo1-path", repoPath || "/pgbackrest");
	}

	// standby backup
	const standby = backupStandby(env.get("PGBACKREST_BACKUP_STANDBY"));
	if (standby) b.set("backup-standby", standby);

	// stanza
	b.blank();
	const stanza = b.section(STANZA);
	stanza.set("pg1-path", PGDATA);
	stanza.set("pg1-port", PG_PORT);
	stanza.set("pg1-user", PG_USER);
	stanza.set("pg1-socket-path", PGRUN);
	stanza.setFromEnv("PGBACKREST_PASSWORD", "pg1-password");
	return b.build();
}

