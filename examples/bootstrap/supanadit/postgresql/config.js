// pgBackRest config: domain-specific env mapping (REPO_* -> repo1-*, snake to
// kebab, plus truthy flags -> "=y"). Not expressible as a generic NameTransform.
function backupStandby(value) {
	switch ((value || "").toLowerCase()) {
		case "y":
		case "yes":
		case "1":
		case "on":
		case "true":
			return "y";
		case "prefer":
			return "prefer";
		case "n":
		case "no":
		case "0":
		case "off":
		case "false":
			return "n";
		default:
			return "";
	}
}

