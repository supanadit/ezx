// Declarative FileProvision rules consumed by the database node.
const postgresFiles = [
	// postgresql.conf: create once if missing, then env overrides (smart-quoted).
	{
		path: POSTGRES_CONF,
		createOnly: true,
		operations: [{ type: "replace", value: postgresqlConfTemplate }],
	},
	{
		path: POSTGRES_CONF,
		operations: [
			{
				type: "set-property",
				fromEnvPattern: "^POSTGRESQL_CONFIG_(.+)$",
				nameTransform: "lower",
				pattern: "^\\s*#?\\s*${name}\\s*=.*",
				value: "${name} = ${value}",
				valueFormat: "auto",
			},
			{
				type: "set-property",
				fromEnv: "POSTGRESQL_SHARED_BUFFERS",
				pattern: "^shared_buffers\\s*=.*",
				value: "shared_buffers = ${value}",
				valueFormat: "auto",
			},
			{
				type: "set-property",
				fromEnv: "POSTGRESQL_MAX_CONNECTIONS",
				pattern: "^max_connections\\s*=.*",
				value: "max_connections = ${value}",
				valueFormat: "auto",
			},
			{
				type: "set-property",
				fromEnv: "POSTGRESQL_LISTEN_ADDRESSES",
				pattern: "^listen_addresses\\s*=.*",
				value: "listen_addresses = ${value}",
				valueFormat: "auto",
			},
			{
				type: "set-property",
				fromEnv: "POSTGRESQL_WORK_MEM",
				pattern: "^work_mem\\s*=.*",
				value: "work_mem = ${value}",
				valueFormat: "auto",
			},
		],
	},
	// pg_hba.conf: default once if missing, then external-access + PG_HBA_ADD_*.
	{
		path: PG_HBA,
		createOnly: true,
		operations: [{ type: "replace", value: pgHbaTemplate }],
	},
	{
		path: PG_HBA,
		operations: [
			{
				type: "set-property",
				when: { name: "EXTERNAL_ACCESS_ENABLE", value: "true" },
				pattern: "^host\\s+all\\s+all\\s+0\\.0\\.0\\.0/0.*",
				value:
					"host    all             all             0.0.0.0/0               " +
					env.get("EXTERNAL_ACCESS_METHOD", "md5"),
			},
			{
				type: "append",
				fromEnvPattern: "^PG_HBA_ADD_([0-9]+)$",
				value: "${value}",
			},
		],
	},
	// pgbackrest.conf: generated by JS (domain-specific PGBACKREST_* mapping,
	// e.g. REPO_* -> repo1-*, is not expressible as a generic NameTransform).
	{
		path: PGBACKREST_CONF,
		when: { name: "PGBACKREST_ENABLE", value: "true" },
		operations: [{ type: "replace", value: pgbackrestConfig() }],
	},
	// patroni.yml, conditional on PATRONI_ENABLE.
	{
		path: PATRONI_CONF,
		when: { name: "PATRONI_ENABLE", value: "true" },
		operations: [{ type: "replace", value: patroniYaml }],
	},
	// sshd_config.
	{ path: SSHD_CONF, operations: [{ type: "replace", value: sshdTemplate }] },
	// pgbouncer.ini env sub (only if enabled).
	{
		path: PGBOUNCER_INI,
		when: { name: "PGBOUNCER_ENABLE", value: "true" },
		operations: [
			{
				type: "set-property",
				fromEnvPattern: "^PGBOUNCER_CONFIG_(.+)$",
				nameTransform: "lower",
				pattern: "^${name}\\s*=.*",
				value: "${name} = ${value}",
			},
		],
	},
];

